"""Host regression fixtures for the parser and the native preview sizing."""
import base64
import ctypes
import os
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile
import unittest
import zlib

SOURCE = Path(__file__).resolve().parents[3] / "experimental/native-display/thumbnail.c"

LVGL_FIXTURE = r"""
#include <stdint.h>
#include <stdlib.h>

struct image { int16_t width, height; uint16_t zoom; uint8_t mode; };
int16_t lv_obj_get_self_width(struct image *img) {
    return img->mode ? img->width * img->zoom / 256 : img->width;
}
int16_t lv_obj_get_self_height(struct image *img) {
    return img->mode ? img->height * img->zoom / 256 : img->height;
}
uint16_t lv_img_get_zoom(struct image *img) { return img->zoom; }
void lv_img_set_zoom(struct image *img, uint16_t zoom) { img->zoom = zoom; }
void lv_img_set_size_mode(struct image *img, uint8_t mode) { img->mode = mode; }
void lv_img_set_src(struct image *img, const int16_t *dimensions) {
    img->width = dimensions[0];
    img->height = dimensions[1];
}
void dispose_thumbnail(char *data) { free(data); }
"""


def chunk(kind, payload):
    return struct.pack(">I", len(payload)) + kind + payload + struct.pack(">I", zlib.crc32(kind + payload))


def preview(size, comment=b""):
    scanlines = (b"\0" + b"\x10\x60\xa0\xff" * size) * size
    header = struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"tEXt", b"Comment\0" + comment)
            + chunk(b"IDAT", zlib.compress(scanlines)) + chunk(b"IEND", b""))


def gcode(size, encoded):
    payload = [b"; " + encoded[i:i + 78] for i in range(0, len(encoded), 78)]
    return b"\n".join([b"; generated by slicer", b"; thumbnail begin %dx%d %d" % (size, size, len(encoded)),
                       *payload, b"; thumbnail end", b"G1 X0\n"])


class Image(ctypes.Structure):
    _fields_ = [("width", ctypes.c_int16), ("height", ctypes.c_int16),
                ("zoom", ctypes.c_uint16), ("mode", ctypes.c_uint8)]


class ThumbnailTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cc = shutil.which("cc")
        if not cc:
            raise unittest.SkipTest("host C compiler unavailable")
        temporary = tempfile.TemporaryDirectory()
        cls.addClassCleanup(temporary.cleanup)
        cls.root = Path(temporary.name)
        stubs = cls.root / "lvgl.c"
        stubs.write_text(LVGL_FIXTURE, encoding="ascii")
        library = cls.root / "thumbnail.so"
        subprocess.run([cc, "-std=c99", "-Wall", "-Wextra", "-Werror", "-fPIC", "-shared",
                        str(SOURCE), str(stubs), "-o", str(library)], check=True, timeout=30)
        cls.lib = ctypes.CDLL(str(library))
        cls.lib.cc2_extract_thumbnail.argtypes = [ctypes.c_char_p]
        cls.lib.cc2_extract_thumbnail.restype = ctypes.c_void_p
        cls.lib.dispose_thumbnail.argtypes = [ctypes.c_void_p]
        cls.lib.dispose_thumbnail.restype = None
        cls.lib.cc2_set_thumbnail_src.argtypes = [ctypes.POINTER(Image), ctypes.POINTER(ctypes.c_int16)]
        cls.lib.cc2_set_thumbnail_zoom.argtypes = [ctypes.POINTER(Image), ctypes.c_uint16]

    def extract(self, raw):
        file = self.root / "plate.gcode"
        file.write_bytes(raw)
        address = self.lib.cc2_extract_thumbnail(os.fsencode(file))
        if not address:
            return None
        try:
            return ctypes.string_at(address)
        finally:
            self.lib.dispose_thumbnail(address)

    def test_reads_past_300_lines(self):
        png = preview(512, b"x" * 19000)
        encoded = base64.b64encode(png)
        self.assertGreater(len(encoded), 300 * 78)
        self.assertEqual(self.extract(gcode(512, encoded)), encoded)

    def test_existing_small_thumbnails_including_crlf(self):
        png = preview(144)
        encoded = base64.b64encode(png)
        source = gcode(144, encoded)
        self.assertLess(len(encoded), 300 * 78)
        self.assertEqual(self.extract(source), encoded)
        self.assertEqual(self.extract(source.replace(b"\n", b"\r\n")), encoded)

    def test_incomplete_or_malformed_blocks_use_fallback(self):
        encoded = base64.b64encode(preview(144))
        source = gcode(144, encoded)
        for invalid in (
            source[:source.index(b"; thumbnail end")],
            source.replace(b"; thumbnail end", b"; " + b"A" * 4 + b"\n; thumbnail end"),
            source.replace(encoded[:78], encoded[:77], 1),
            source.replace(encoded[:78], b"!" + encoded[1:78], 1),
            gcode(240, encoded),
            gcode(2048, base64.b64encode(preview(2048))),
            source.replace(b" %d\n" % len(encoded), b" 1048580\n"),
            b"; no thumbnail\nG1 X0\n",
        ):
            with self.subTest(length=len(invalid)):
                self.assertIsNone(self.extract(invalid))

    def test_large_images_keep_the_native_preview_bounds(self):
        image = Image(0, 0, 256, 0)
        dimensions = ctypes.c_int16 * 2
        self.lib.cc2_set_thumbnail_src(ctypes.byref(image), dimensions(512, 384))
        self.assertEqual((image.zoom, image.mode), (72, 1))
        image.zoom = 128  # The native file-list view sets its nominal zoom before loading.
        self.lib.cc2_set_thumbnail_src(ctypes.byref(image), dimensions(144, 144))
        self.assertEqual((image.zoom, image.mode), (128, 0))
        history = Image(512, 384, 256, 0)
        self.lib.cc2_set_thumbnail_zoom(ctypes.byref(history), 80)
        self.assertEqual((history.zoom, history.mode), (22, 1))


if __name__ == "__main__":
    unittest.main()
